#include "../firmware/social_reactions.h"
#include "../firmware/face_engine.h"
#include <cassert>
#include <iostream>
using namespace espen;
int main(){
    assert(ClassifySocial("JESTEŚ SUPER!") == Social::Praise);
    assert(ClassifySocial("Ala, kocham Cię.") == Social::Affection);
    assert(ClassifySocial("Dziękuję!") == Social::Thanks);
    assert(ClassifySocial("Przybij piątkę!") == Social::Celebration);
    assert(ClassifySocial("Dzień dobry!") == Social::Greeting);
    assert(ClassifySocial("Dobranoc") == Social::Goodnight);
    assert(ClassifySocial("Nie jesteś super") == Social::None);
    assert(ClassifySocial("Czy jesteś super?") == Social::None);
    assert(ClassifySocial("Powiedz kocham cię po angielsku") == Social::None);
    assert(ClassifySocial("Supermarket jest otwarty") == Social::None);
    assert(ClassifySocial("Jest mi smutno")==Social::Comfort);
    assert(ClassifySocial("Jestem zmęczona")==Social::Comfort);
    assert(ClassifySocial("Przytul mnie")==Social::Affection);
    assert(ClassifySocial("Nie lubię cię")==Social::Annoyed);
    assert(ClassifySocial("Przepraszam")==Social::Apology);
    assert(ClassifySocial("Czy jesteś głupia?")==Social::None);
    Affinity a;
    a.Record(Social::Praise,100);assert(a.Effect(200)==PetEffect::Flower);
    a.Record(Social::Affection,500);assert(a.Effect(600)==PetEffect::Flower);
    a.Record(Social::Thanks,2000);a.Record(Social::Praise,4000);
    assert(a.Effect(4050)==PetEffect::Bouquet);
    assert(a.Effect(7000)==PetEffect::None);
    a.Record(Social::Annoyed,7000);a.Record(Social::Annoyed,9000);a.Record(Social::Annoyed,11000);
    assert(a.Effect(11100)==PetEffect::Volcano);
    a.Record(Social::Apology,11200);assert(a.Effect(11300)==PetEffect::None);
    ListeningLayout layout;
    for(int i=0;i<10;++i)layout.Tick(true,100,i*50);
    assert(layout.shift==-42&&layout.heights[2]>90);
    for(int i=0;i<10;++i)layout.Tick(false,0,i*50);
    assert(layout.shift==0&&layout.level==0&&layout.heights[2]==26);
    PetMotion p;
    p.Begin(10,20,100);
    assert(p.Move(12,21,200)==Motion::None);
    assert(p.Move(50,20,400)==Motion::Stroke);
    assert(p.Move(180,20,900)==Motion::Stroke);
    p.Begin(100,100,1000);
    p.Move(125,100,1100);p.Move(100,100,1200);p.Move(125,100,1300);
    assert(p.Move(100,100,1400)==Motion::Tickle);
    auto h=HeartAt(500,0,180,180);
    assert(h.visible&&h.y<180&&h.opacity>0);
    assert(!HeartAt(0,5,180,180).visible);
    assert(!HeartAt(1900,5,180,180).visible);
    FaceEngine e;
    e.Tick(100,Phase::Idle,0,MouthShape::Closed);
    e.SocialReact(Social::Affection,200);
    auto f=e.Tick(300,Phase::Thinking,0,MouthShape::Closed);
    assert(f.mood==Mood::Love&&f.hearts);
    for(uint32_t t=400;t<1000;t+=50)f=e.Tick(t,Phase::Speaking,120,MouthShape::Round);
    assert(f.mood==Mood::Love&&f.pose.mouth_h>20&&f.pose.smile==0&&f.hearts);
    e.SocialReact(Social::Praise,1200);
    assert(e.Tick(1250,Phase::Speaking,80,MouthShape::Open).mood==Mood::Happy);
    assert(!e.Tick(4500,Phase::Idle,0,MouthShape::Closed).hearts);
    e.React(Gesture::Stroke,5000);
    assert(e.Tick(5100,Phase::Idle,0,MouthShape::Closed).hearts);
    e.React(Gesture::TripleTap,5200);
    assert(e.Tick(5300,Phase::Idle,0,MouthShape::Closed).mood==Mood::Excited);
    e.React(Gesture::Boop,5400);
    assert(e.Tick(5450,Phase::Idle,0,MouthShape::Closed).mood==Mood::Shy);
    e.React(Gesture::DoubleTap,5500);
    assert(e.Tick(5550,Phase::Idle,0,MouthShape::Closed).mood==Mood::Surprise);
    FaceEngine pet;
    pet.Tick(100,Phase::Idle,0,MouthShape::Closed);
    pet.SocialReact(Social::Comfort,200);
    assert(pet.Tick(1000,Phase::Thinking,0,MouthShape::Closed).hearts);
    pet.SocialReact(Social::Annoyed,1500);
    assert(pet.Tick(1550,Phase::Speaking,120,MouthShape::Open).mood==Mood::Angry);
    pet.SocialReact(Social::Apology,2000);
    assert(pet.Tick(2100,Phase::Speaking,120,MouthShape::Open).mood==Mood::Happy);
    FaceEngine sleeping;
    sleeping.Tick(100,Phase::Idle,0,MouthShape::Closed);
    assert(sleeping.Tick(5200,Phase::Idle,0,MouthShape::Closed).asleep);
    auto surprised=sleeping.Tick(5300,Phase::Idle,0,MouthShape::Closed,true);
    assert(!surprised.asleep&&surprised.mood==Mood::Surprise);
    std::cout<<"Espen social reaction tests passed\n";
}
